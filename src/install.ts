import { createHash, randomUUID } from "node:crypto";
import { chmodSync, existsSync, lstatSync, mkdirSync, readFileSync, readlinkSync, realpathSync, renameSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const files = ["src/cli.ts", "src/core.ts", "src/install.ts", "src/rtk.ts", "src/guide.ts", "data/skills-v5.json", "examples/usage.json", "skills/agent-token-saver/SKILL.md", "package.json", "README.md", "docs/GUIDE.md", "docs/RTK.md", "docs/MIGRATION.md", "docs/CONCEPT.md", "docs/SKILLS.md", "docs/SPEED.md", "docs/BENCHMARK_REVIEW.md", "docs/QUICKSTART.en.md", "docs/RELEASE-5.1.1.md", "data/research/speed-review-2026-11-12.json"];
const hash = (body: string) => createHash("sha256").update(body).digest("hex");
const names = ["agent-token-saver", "ats"];
function entryExists(path: string): boolean {
  try { lstatSync(path); return true; }
  catch (error) {
    if (error && typeof error === "object" && "code" in error && error.code === "ENOENT") return false;
    throw error;
  }
}
function atomicLink(target: string, path: string) {
  const temporary = `${path}.${randomUUID()}`;
  symlinkSync(target, temporary);
  renameSync(temporary, path);
}

type SavedEntry = { name: string; kind: "absent" | "file" | "link"; value: string | null; mode: number };
type Receipt = { id: string; previous: string | null; release: string; entries: SavedEntry[] };
function managedPrevious(store: string) {
  const current = join(store, "current");
  if (!entryExists(current)) return null;
  if (!lstatSync(current).isSymbolicLink()) throw new Error("Unmanaged current directory");
  const previous = readlinkSync(current);
  if (!previous.startsWith(`${join(store, "releases")}/`) || !existsSync(current)) throw new Error("Unmanaged or broken current pointer");
  return previous;
}

export function install(home = homedir(), dryRun = true) {
  const target = resolve(home);
  const store = join(target, ".agent-token-saver-v5");
  const current = join(store, "current");
  const contents = files.map(path => ({ path, body: readFileSync(join(root, path), "utf8") }));
  const id = randomUUID();
  const release = join(store, "releases", id);
  const launchers = names.map(name => join(target, ".local", "bin", name));
  const plan = { dry_run: dryRun, id, release, launchers, host_config_changes: false };
  if (dryRun) return plan;
  const previous = managedPrevious(store);
  // Read and validate user-owned starters before activating anything.
  const entries: SavedEntry[] = launchers.map((path, i) => {
    if (!entryExists(path)) return { name: names[i]!, kind: "absent", value: null, mode: 0 };
    const stat = lstatSync(path);
    if (stat.isSymbolicLink()) return { name: names[i]!, kind: "link", value: readlinkSync(path), mode: 0 };
    if (!stat.isFile()) throw new Error(`Refusing non-file starter: ${path}`);
    return { name: names[i]!, kind: "file", value: readFileSync(path).toString("base64"), mode: stat.mode & 0o777 };
  });
  for (const file of contents) {
    const output = join(release, file.path);
    mkdirSync(dirname(output), { recursive: true, mode: 0o700 });
    writeFileSync(output, file.body, { mode: file.path === "src/cli.ts" ? 0o700 : 0o600, flag: "wx" });
  }
  writeFileSync(join(release, "manifest.json"), JSON.stringify(Object.fromEntries(contents.map(x => [x.path, hash(x.body)]))), { mode: 0o600 });
  const receipt: Receipt = { id, previous, release, entries };
  mkdirSync(join(store, "receipts"), { recursive: true, mode: 0o700 });
  writeFileSync(join(store, "receipts", `${id}.json`), JSON.stringify(receipt), { mode: 0o600, flag: "wx" });
  mkdirSync(join(target, ".local", "bin"), { recursive: true });
  // Each pointer swap is atomic. Receipt permits recovery after an interrupted multi-pointer update.
  atomicLink(release, current);
  for (const path of launchers) atomicLink(join(current, "src", "cli.ts"), path);
  return { ...plan, receipt: join(store, "receipts", `${id}.json`), rollback_id: id,
    rollback_argv: [process.execPath, join(root, "src", "cli.ts"), "rollback", "--home", target, "--id", id, "--apply"] };
}

export function rollback(home: string, id: string, apply: boolean) {
  if (!/^[a-f0-9-]{36}$/.test(id)) throw new Error("Invalid installation id");
  const target = resolve(home);
  const store = join(target, ".agent-token-saver-v5");
  const data: unknown = JSON.parse(readFileSync(join(store, "receipts", `${id}.json`), "utf8"));
  if (!data || typeof data !== "object" || !("id" in data) || data.id !== id) throw new Error("Invalid receipt");
  const receipt = data as Receipt;
  // Only IDs generated by this installer can name a release. Receipts are private local recovery data.
  if (receipt.release !== join(store, "releases", id) || !Array.isArray(receipt.entries) || receipt.entries.length !== names.length) throw new Error("Invalid receipt paths");
  const current = join(store, "current");
  if (!entryExists(current) || readlinkSync(current) !== receipt.release) throw new Error("A newer or foreign generation is active; refusing rollback");
  for (const [index, entry] of receipt.entries.entries()) {
    if (entry.name !== names[index] || !["absent", "file", "link"].includes(entry.kind)) throw new Error("Invalid receipt entries");
    if (entry.kind !== "absent" && typeof entry.value !== "string") throw new Error("Invalid recovery value");
    const path = join(target, ".local", "bin", entry.name);
    if (!entryExists(path) || !lstatSync(path).isSymbolicLink() || readlinkSync(path) !== join(current, "src", "cli.ts")) throw new Error(`Starter changed: ${entry.name}`);
  }
  if (receipt.previous !== null && (!receipt.previous.startsWith(`${join(store, "releases")}/`) || !existsSync(receipt.previous))) throw new Error("Previous release unavailable");
  if (!apply) return { dry_run: true, id, restored_launchers: names };
  for (const entry of receipt.entries) {
    const path = join(target, ".local", "bin", entry.name);
    if (entry.kind === "absent") rmSync(path);
    else if (entry.kind === "link") atomicLink(entry.value!, path);
    else {
      const temporary = `${path}.${randomUUID()}`;
      writeFileSync(temporary, Buffer.from(entry.value!, "base64"), { mode: entry.mode, flag: "wx" });
      chmodSync(temporary, entry.mode);
      renameSync(temporary, path);
    }
  }
  if (receipt.previous) atomicLink(receipt.previous, current); else rmSync(current);
  return { dry_run: false, id, restored_launchers: names, generations_retained: true };
}

export function doctor(home = homedir()) {
  const store = join(resolve(home), ".agent-token-saver-v5");
  const current = join(store, "current");
  if (!existsSync(current)) return { passed: false, status: "not-installed", checks: [], launchers_match: false, runtime: `bun ${Bun.version}`, host_hooks: "not managed", live_host_acceptance: false };
  const release = realpathSync(current);
  if (!release.startsWith(`${realpathSync(join(store, "releases"))}/`)) throw new Error("Unmanaged release");
  const manifest: unknown = JSON.parse(readFileSync(join(release, "manifest.json"), "utf8"));
  if (!manifest || typeof manifest !== "object" || Array.isArray(manifest)) throw new Error("Invalid manifest");
  const expected = manifest as Record<string, unknown>;
  const checks = files.map(path => ({ path, matches: typeof expected[path] === "string" && existsSync(join(release, path)) && hash(readFileSync(join(release, path), "utf8")) === expected[path] }));
  const launchersMatch = names.every(name => {
    const path = join(resolve(home), ".local", "bin", name);
    return entryExists(path) && lstatSync(path).isSymbolicLink() && readlinkSync(path) === join(current, "src", "cli.ts");
  });
  return { passed: checks.every(x => x.matches) && launchersMatch, status: "checked", checks, launchers_match: launchersMatch,
    runtime: `bun ${Bun.version}`, host_hooks: "not managed", live_host_acceptance: false };
}
